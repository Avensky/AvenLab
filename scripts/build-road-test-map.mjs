import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
import {emptyLayout,addPiece} from '../frontend/src/worldBuilder/layoutDocument.ts';
import {opposingRoadPair} from '../frontend/src/worldBuilder/roads/roadPair.ts';
import {mapExport} from '../frontend/src/worldBuilder/mapDocument.ts';
const source=JSON.parse(fs.readFileSync(new URL('../avenlab-server/src/assets/blocks/streaming_endless_city_colliders.json',import.meta.url),'utf8'));
let doc=addPiece(emptyLayout('road_precision'),'glb-road_narrow',[0,0,0]);
doc=opposingRoadPair(doc,doc.objects[0].id);
doc=addPiece(doc,'glb-road_wide',[145,0,0]);
doc=addPiece(doc,'glb-intersection',[-120,0,0]);
doc.title='Road precision test';doc.ground=false;doc.repeat=false;
const map=mapExport({...source,map_id:'road_precision',authored_layout:doc}),output=new URL('../avenlab-server/src/assets/blocks/road_precision_colliders.json',import.meta.url);
if(process.argv.includes('--check')){if(fs.readFileSync(output,'utf8')!==map)throw Error('Road test map is stale');}else fs.writeFileSync(output,map);
console.log(`Road proving ground: ${doc.objects.length} modules, one district, no fallback floor (${fileURLToPath(output)})`);
